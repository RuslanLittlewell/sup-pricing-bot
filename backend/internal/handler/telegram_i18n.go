func tr(lang, key string) string {
	if texts, ok := botTexts[lang]; ok {
		if text, ok := texts[key]; ok {
			return text
		}
	}
	return botTexts[defaultBotLanguage][key]
}

func validBotLanguage(lang string) string {
	switch lang {
	case "ru", "en", "pl":
		return lang
	default:
		return defaultBotLanguage
	}
}
