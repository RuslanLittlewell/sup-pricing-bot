func TestIsBotChallengeDetectsWordfenceBlock(t *testing.T) {
	// Wordfence localises every visible string on this page, so detection keys off the
	// documentation link its WAF block templates hardcode instead. This body is the
	// Polish variant supermaluch.com actually served us.
	body := []byte(`<html><head><title>Twój dostęp do tej witryny został ograniczony przez właściciela witryny</title></head>
<body><div class="container"><h1>Twój dostęp do tej witryny został ograniczony przez właściciela witryny</h1>
<p class="documentation small">Kliknij tutaj, aby dowiedzieć się więcej:
<a href="https://www.wordfence.com/help/?query=locked-out" target="_blank" rel="noopener noreferrer">Dokumentacja</a></p>
</div></body></html>`)

	if !isBotChallenge(body) {
		t.Fatal("Wordfence block page must not reach the price parsers as a successful fetch")
	}
}

